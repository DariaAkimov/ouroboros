# --- Утилиты нормализации текста --------------------------------------------
def _norm(s: object) -> str:
    """Нижний регистр, NBSP→пробел, ё→е, схлопывание пробелов."""
    s = str(s).replace("\xa0", " ").lower().replace("ё", "е")
    s = re.sub(r"\s+", " ", s).strip()
    return s


# --- B.3 функции ролей -------------------------------------------------------
def role_tier(role: object) -> Optional[str]:
    """Старшинство роли (T1..T5) = max совпавшего маркера (B.3)."""
    r = _norm(role)
    if not r:
        return None
    for tier, markers in ROLE_TIER_MARKERS:
        for m in markers:
            if m in r:
                return tier
    return None


# Порядок тиров для сравнения «на тир ниже».
TIER_ORDER = ["T1", "T2", "T3", "T4", "T5"]


def tier_index(tier: Optional[str]) -> Optional[int]:
    return TIER_ORDER.index(tier) if tier in TIER_ORDER else None


def one_tier_below(tier: Optional[str]) -> List[str]:
    """Тиры, считающиеся «на ступень ниже» целевого (для лонг-листа преемников)."""
    idx = tier_index(tier)
    if idx is None:
        return []
    below = []
    if idx + 1 < len(TIER_ORDER):
        below.append(TIER_ORDER[idx + 1])
    if idx + 2 < len(TIER_ORDER):
        below.append(TIER_ORDER[idx + 2])
    return below


def role_family(role: object) -> Optional[str]:
    """Функциональное семейство роли по ключевым словам (B.3, сид)."""
    r = _norm(role)
    if not r:
        return None
    best, best_hits = None, 0
    for fam, kws in ROLE_FAMILY_KEYWORDS.items():
        hits = sum(1 for kw in kws if _norm(kw) in r)
        if hits > best_hits:
            best, best_hits = fam, hits
    return best


# --- B.1 функции блоков ------------------------------------------------------
def match_block_synonym(query: object) -> Optional[str]:
    """Сопоставляет формулировку блока с каноном по синонимам (сид).

    Возвращает каноническое имя блока ИЗ СИДА (которое затем обязательно
    сверяется с фактическими значениями данных вызывающей стороной).
    """
    q = _norm(query)
    if not q:
        return None
    # Прямое вхождение канона.
    for canon in BLOCK_SYNONYMS:
        if _norm(canon) in q or q in _norm(canon):
            return canon
    # По синонимам (более длинные синонимы — раньше, чтобы избежать ложных коротких).
    pairs = []
    for canon, syns in BLOCK_SYNONYMS.items():
        for s in syns:
            pairs.append((s, canon))
    pairs.sort(key=lambda p: len(p[0]), reverse=True)
    for s, canon in pairs:
        if re.search(r"(?<![а-яёa-z])" + re.escape(_norm(s)) + r"(?![а-яёa-z])", q):
            return canon
    return None


def nonexistent_block_hint(query: object) -> Optional[Dict[str, object]]:
    """Если запрос называет отсутствующий блок («Финансы» и т. п.) — вернуть подсказку."""
    q = _norm(query)
    for key, hint in NONEXISTENT_BLOCK_HINTS.items():
        if key in q:
            return hint
    return None


def match_role_title(query: object) -> Optional[Dict[str, object]]:
    """Маппинг англоязычной/неформальной должности на блок/семейство/якорные роли (B.4)."""
    q = _norm(query)
    if not q:
        return None
    for m in ROLE_TITLE_MAPPINGS:
        for alias in m["aliases"]:
            if _norm(alias) in q:
                return m
    return None


