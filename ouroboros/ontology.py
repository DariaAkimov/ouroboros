def is_strategy_facilitation(name: object) -> bool:
    n = _norm(name)
    return any(_norm(kw) in n for kw in STRATEGY_FACILITATION_KEYWORDS)


def interest_category(name: object) -> Optional[str]:
    n = _norm(name)
    for c, kws in INTEREST_CATEGORIES.items():
        if any(kw in n for kw in kws):
            return c
    return None
